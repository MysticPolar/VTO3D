/**
 * Generates src/components/Icon/icons.ts from the prototype's icon set (HANDOFF §5.5):
 * reference/prototype/js/icons.js, name → its stroke shapes (`s`) and filled shapes (`f`).
 * Re-run after the prototype's icons change:  node scripts/icons/generate.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { runInNewContext } from 'node:vm';

interface Shape {
  s?: string;
  f?: string;
}

const ROOT = join(import.meta.dirname, '..', '..');
const SOURCE = join(ROOT, 'reference', 'prototype', 'js', 'icons.js');
const OUT = join(ROOT, 'src', 'components', 'Icon', 'icons.ts');

// icons.js keeps its shapes in a private `P`; expose it next to VT.icon
const source = readFileSync(SOURCE, 'utf8');
const exposed = source.replace('VT.icon = icon;', 'VT.icon = icon; VT.iconShapes = P;');
if (exposed === source) throw new Error('icons.js changed: "VT.icon = icon;" is gone');

const window: { VT?: { iconShapes?: Record<string, Shape> } } = {};
runInNewContext(exposed, { window, console });
const shapes = window.VT?.iconShapes;
if (!shapes) throw new Error('icons.js defined no icons');

const body = Object.entries(shapes)
  .map(([name, shape]) => `  ${JSON.stringify(name)}: ${JSON.stringify(shape)},`)
  .join('\n');
writeFileSync(
  OUT,
  `// Generated by scripts/icons/generate.ts from reference/prototype/js/icons.js. Do not edit.\n\n` +
    `export const ICONS = {\n${body}\n} satisfies Record<string, { s?: string; f?: string }>;\n\n` +
    `export type IconName = keyof typeof ICONS;\n`,
);
console.log(`${Object.keys(shapes).length} icons → ${relative(ROOT, OUT)}`);
